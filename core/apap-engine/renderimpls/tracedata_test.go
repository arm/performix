func TestTraceDataRendererInsertsTracksAndSourcesInDependencyOrder(t *testing.T) {
	model := cdf.NewOnDiskModel(t.TempDir(), &cdf.Manifest{}, cdf.Metadata{})
	session := newSQLTestSession(t, model, "run1")
	parent := addTraceTestTable(t, session, TraceSpanFragmentComponentName,
		`source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR`,
		`('parent-late', 100, 200, 0, 'parent late'), ('parent-early', 0, 90, 0, 'parent early')`)
	child := addTraceTestTable(t, session, TraceSpanFragmentComponentName,
		`source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR, parent_source_event_id VARCHAR`,
		`('child-late', 130, 180, 0, 'child late', 'parent-late'), ('child-early', 10, 80, 0, 'child early', 'parent-early')`)
	renderer := &TraceDataRenderer{}
	require.NoError(t, renderer.Configure(&render.Config{Identity: render.RendererIdentity{Name: "trace"}, JSON: `{
      "tracks":[
        {"key":"child","parent":"root","name":"Child","kind":"span"},
        {"key":"parent","parent":"root","name":"Parent","kind":"span"},
        {"key":"root","name":"Root","kind":"group"}
      ],
      "spans":[
        {"input":"child","track":"child","parent_source":"parent"},
        {"input":"parent","track":"parent"}
      ]
    }`}))
	require.NoError(t, renderer.Initialize(session, map[string][]render.TableRef{
		"parent": {{Name: parent}}, "child": {{Name: child}},
	}))

	spans := findTraceOutputTable(t, session, TraceSpansComponentName)
	// #nosec G201 -- spans is a quoted table name generated by the render manifest.
	query := fmt.Sprintf(`SELECT track_id, start_ns FROM %s`, sqlDoubleQuoteString(spans))
	rows, err := session.Database().Conn.QueryContext(context.Background(),
		query)
	require.NoError(t, err)
	defer rows.Close()
	var got [][2]int64
	for rows.Next() {
		var trackID, startNS int64
		require.NoError(t, rows.Scan(&trackID, &startNS))
		got = append(got, [2]int64{trackID, startNS})
	}
	require.NoError(t, rows.Err())
	require.Equal(t, [][2]int64{{2, 0}, {2, 100}, {3, 10}, {3, 130}}, got)

	tracks := findTraceOutputTable(t, session, TraceTracksComponentName)
	var parentTrackID, childTrackID int64
	require.NoError(t, session.Database().Conn.QueryRowContext(context.Background(),
		`SELECT MIN(track_id) FILTER (WHERE name = 'Parent'), MIN(track_id) FILTER (WHERE name = 'Child') FROM `+tracks).
		Scan(&parentTrackID, &childTrackID))
	require.Equal(t, int64(2), parentTrackID)
	require.Equal(t, int64(3), childTrackID)
}

func TestTraceDataRendererRejectsNonGroupTrackParent(t *testing.T) {
	renderer := &TraceDataRenderer{}
	err := renderer.Configure(&render.Config{Identity: render.RendererIdentity{Name: "trace"}, JSON: `{
      "tracks":[
        {"key":"parent","name":"Parent","kind":"span"},
        {"key":"child","parent":"parent","name":"Child","kind":"span"}
      ]
    }`})
	require.ErrorContains(t, err, `trace track "child" references non-group parent "parent"`)
	requireTraceRendererMessage(t, err, message.EngineRenderTraceDataRendererConfigInvalid, map[string]string{
		"rendererName": "trace",
	})
}

func TestTraceDataRendererConstraintsRejectInvalidInput(t *testing.T) {
	t.Run("duplicate source event ID", func(t *testing.T) {
		model := cdf.NewOnDiskModel(t.TempDir(), &cdf.Manifest{}, cdf.Metadata{})
		session := newSQLTestSession(t, model, "run1")
		spans := addTraceTestTable(t, session, TraceSpanFragmentComponentName,
			`source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR`,
			`('duplicate', 0, 10, 0, 'one'), ('duplicate', 10, 20, 0, 'two')`)
		renderer := &TraceDataRenderer{}
		require.NoError(t, renderer.Configure(&render.Config{Identity: render.RendererIdentity{Name: "trace"}, JSON: `{
          "tracks":[{"key":"spans","name":"Spans","kind":"span"}],
          "spans":[{"input":"spans","track":"spans"}]
        }`}))
		err := renderer.Initialize(session, map[string][]render.TableRef{"spans": {{Name: spans}}})
		require.ErrorContains(t, err, "populate trace event ID map")
		requireTraceRendererMessage(t, err, message.EngineRenderTraceDataRendererMaterializationFailed, map[string]string{
			"rendererName": "trace",
			"operation":    "create event ID map",
		})
	})

	t.Run("reversed interval", func(t *testing.T) {
		model := cdf.NewOnDiskModel(t.TempDir(), &cdf.Manifest{}, cdf.Metadata{})
		session := newSQLTestSession(t, model, "run1")
		spans := addTraceTestTable(t, session, TraceSpanFragmentComponentName,
			`source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR`,
			`('reversed', 20, 10, 0, 'reversed')`)
		renderer := &TraceDataRenderer{}
		require.NoError(t, renderer.Configure(&render.Config{Identity: render.RendererIdentity{Name: "trace"}, JSON: `{
          "tracks":[{"key":"spans","name":"Spans","kind":"span"}],
          "spans":[{"input":"spans","track":"spans"}]
        }`}))
		err := renderer.Initialize(session, map[string][]render.TableRef{"spans": {{Name: spans}}})
		require.ErrorContains(t, err, `insert canonical trace spans from input "spans"`)
		for _, componentName := range []string{
			TraceTracksComponentName,
			TraceSpansComponentName,
			TraceMetadataComponentName,
		} {
			for _, entry := range session.Manifest().Entries() {
				require.NotEqual(t, componentName, entry.Info().ComponentType().Name)
			}
		}
	})
}

func TestTraceDataRendererRejectsIncorrectInputColumnTypes(t *testing.T) {
	t.Run("source event ID", func(t *testing.T) {
		model := cdf.NewOnDiskModel(t.TempDir(), &cdf.Manifest{}, cdf.Metadata{})
		session := newSQLTestSession(t, model, "run1")
		spans := addTraceTestTable(t, session, TraceSpanFragmentComponentName,
			`source_event_id BIGINT, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR`,
			`(1, 0, 10, 0, 'span')`)
		renderer := &TraceDataRenderer{}
		require.NoError(t, renderer.Configure(&render.Config{Identity: render.RendererIdentity{Name: "trace"}, JSON: `{
          "tracks":[{"key":"spans","name":"Spans","kind":"span"}],
          "spans":[{"input":"spans","track":"spans"}]
        }`}))
		err := renderer.Initialize(session, map[string][]render.TableRef{"spans": {{Name: spans}}})
		require.ErrorContains(t, err, `column "source_event_id" must have type VARCHAR, got BIGINT`)
		requireTraceRendererMessage(t, err, message.EngineRenderTraceDataRendererInputInvalid, map[string]string{
			"rendererName": "trace",
		})
	})

	for _, test := range []struct {
		name, columns, expected string
	}{
		{
			name:     "required span column",
			columns:  `source_event_id VARCHAR, start_ns INTEGER, end_ns BIGINT, row UINTEGER, name VARCHAR`,
			expected: `column "start_ns" must have type BIGINT, got INTEGER`,
		},
		{
			name:     "optional span column",
			columns:  `source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR, flags INTEGER`,
			expected: `column "flags" must have type UINTEGER, got INTEGER`,
		},
		{
			name:     "metadata column",
			columns:  `source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR, metadata VARCHAR`,
			expected: `column "metadata" must have type JSON, got VARCHAR`,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			model := cdf.NewOnDiskModel(t.TempDir(), &cdf.Manifest{}, cdf.Metadata{})
			session := newSQLTestSession(t, model, "run1")
			spans := addTraceTestTable(t, session, TraceSpanFragmentComponentName, test.columns, "")
			renderer := &TraceDataRenderer{}
			require.NoError(t, renderer.Configure(&render.Config{Identity: render.RendererIdentity{Name: "trace"}, JSON: `{
              "tracks":[{"key":"spans","name":"Spans","kind":"span"}],
              "spans":[{"input":"spans","track":"spans"}]
            }`}))
			err := renderer.Initialize(session, map[string][]render.TableRef{"spans": {{Name: spans}}})
			require.ErrorContains(t, err, test.expected)
		})
	}

	t.Run("parent source event ID", func(t *testing.T) {
		model := cdf.NewOnDiskModel(t.TempDir(), &cdf.Manifest{}, cdf.Metadata{})
		session := newSQLTestSession(t, model, "run1")
		api := addTraceTestTable(t, session, TraceSpanFragmentComponentName,
			`source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR`,
			`('api', 0, 10, 0, 'api')`)
		operators := addTraceTestTable(t, session, TraceSpanFragmentComponentName,
			`source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR, parent_source_event_id BIGINT`,
			`('operator', 1, 9, 0, 'operator', 1)`)
		renderer := &TraceDataRenderer{}
		require.NoError(t, renderer.Configure(&render.Config{Identity: render.RendererIdentity{Name: "trace"}, JSON: traceRendererTestConfig}))
		err := renderer.Initialize(session, map[string][]render.TableRef{
			"api_spans": {{Name: api}}, "operator_spans": {{Name: operators}},
		})
		require.ErrorContains(t, err, `column "parent_source_event_id" must have type VARCHAR, got BIGINT`)
	})
}

