const traceRendererTestConfig = `{
  "tracks": [
    {"key":"root", "name":"Root", "kind":"group"},
    {"key":"api", "parent":"root", "name":"API", "kind":"span"},
    {"key":"operators", "parent":"root", "name":"Operators", "kind":"span"}
  ],
  "spans": [
    {"input":"api_spans", "track":"api"},
    {"input":"operator_spans", "track":"operators", "parent_source":"api_spans"}
  ]
}`

func requireTraceRendererMessage(t *testing.T, err error, code message.MessageCode, metadata map[string]string) {
	t.Helper()
	var got message.Message
	require.ErrorAs(t, err, &got)
	require.Equal(t, code, got.Code())
	for key, value := range metadata {
		require.Equal(t, value, got.Metadata()[key])
	}
	require.NotNil(t, errors.Unwrap(got))
}

func addTraceTestTable(t *testing.T, session render.Session, componentName, createColumns, values string) string {
	t.Helper()
	name := session.Manifest().AddEntry(render.NewManifestEntryInfo(
		cdf.ComponentType{Name: componentName, SchemaVersion: TraceDataSchemaVersion},
		render.RendererIdentity{Name: "source"},
		[]run.RunID{{Value: "run1"}},
	))
	query := fmt.Sprintf(`CREATE TABLE %s (%s)`, name, createColumns)
	if values != "" {
		query += `; INSERT INTO ` + name + ` VALUES ` + values
	}
	_, err := session.Database().Conn.ExecContext(context.Background(), query)
	require.NoError(t, err)
	return name
}

func findTraceOutputTable(t *testing.T, session render.Session, componentName string) string {
	t.Helper()
	for _, entry := range session.Manifest().Entries() {
		if entry.Info().ComponentType().Name == componentName {
			return entry.TableName()
		}
	}
	t.Fatalf("output component %s not found", componentName)
	return ""
}

func TestTraceDataRendererMaterializesCanonicalTables(t *testing.T) {
	model := cdf.NewOnDiskModel(t.TempDir(), &cdf.Manifest{}, cdf.Metadata{})
	session := newSQLTestSession(t, model, "run1")
	api := addTraceTestTable(t, session, TraceSpanFragmentComponentName,
		`source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR, metadata JSON`,
		`('0', 0, 100, 0, 'torch.add', '{"arguments":[1,2]}'), ('1', 200, 300, 0, 'torch.mul', NULL)`)
	operators := addTraceTestTable(t, session, TraceSpanFragmentComponentName,
		`source_event_id VARCHAR, start_ns BIGINT, end_ns BIGINT, row UINTEGER, name VARCHAR, parent_source_event_id VARCHAR, metadata JSON`,
		`('0', 10, 90, 0, 'aten.add', '0', '{"arguments":[1,2]}'), ('2', 210, 290, 0, 'aten.mul', '1', '{"output":{"type":"Tensor"}}')`)

	renderer := &TraceDataRenderer{}
	require.NoError(t, renderer.Configure(&render.Config{
		Identity: render.RendererIdentity{Name: "trace"}, JSON: traceRendererTestConfig,
	}))
	require.NoError(t, renderer.Initialize(session, map[string][]render.TableRef{
		"api_spans":      {{Name: api}},
		"operator_spans": {{Name: operators}},
	}))

	spans := findTraceOutputTable(t, session, TraceSpansComponentName)
	// #nosec G201 -- spans is a quoted table name generated by the render manifest.
	query := fmt.Sprintf(`SELECT event_id, track_id, start_ns, parent_event_id FROM %s ORDER BY event_id`, sqlDoubleQuoteString(spans))
	rows, err := session.Database().Conn.QueryContext(context.Background(),
		query)
	require.NoError(t, err)
	defer rows.Close()
	type spanRow struct {
		eventID, trackID int64
		start            int64
		parent           *int64
	}
	var got []spanRow
	for rows.Next() {
		var row spanRow
		require.NoError(t, rows.Scan(&row.eventID, &row.trackID, &row.start, &row.parent))
		got = append(got, row)
	}
	require.Equal(t, []spanRow{
		{eventID: 0, trackID: 2, start: 0},
		{eventID: 1, trackID: 2, start: 200},
		{eventID: 2, trackID: 3, start: 10, parent: util.Ptr(int64(0))},
		{eventID: 3, trackID: 3, start: 210, parent: util.Ptr(int64(1))},
	}, got)

	tracks := findTraceOutputTable(t, session, TraceTracksComponentName)
	var rootRows, apiRows, operatorRows *uint32
	require.NoError(t, session.Database().Conn.QueryRowContext(context.Background(),
		`SELECT MAX(row_count) FILTER (WHERE track_id=1), MAX(row_count) FILTER (WHERE track_id=2), MAX(row_count) FILTER (WHERE track_id=3) FROM `+tracks,
	).Scan(&rootRows, &apiRows, &operatorRows))
	require.Nil(t, rootRows)
	require.Equal(t, uint32(1), *apiRows)
	require.Equal(t, uint32(1), *operatorRows)

	metadataOutput := findTraceOutputTable(t, session, TraceMetadataComponentName)
	var ownerID int64
	require.NoError(t, session.Database().Conn.QueryRowContext(context.Background(),
		`SELECT owner_id FROM `+metadataOutput+` WHERE key='arguments'`).Scan(&ownerID))
	require.Equal(t, int64(0), ownerID)
	var metadataRows int
	require.NoError(t, session.Database().Conn.QueryRowContext(context.Background(),
		`SELECT COUNT(*) FROM `+metadataOutput).Scan(&metadataRows))
	require.Equal(t, 3, metadataRows)
	var metadataOwnerIDIndexes int
	require.NoError(t, session.Database().Conn.QueryRowContext(context.Background(),
		`SELECT COUNT(*) FROM duckdb_indexes() WHERE table_name = ? AND index_name = ?`,
		metadataOutput, metadataOutput+"_owner_id_idx").Scan(&metadataOwnerIDIndexes))
	require.Equal(t, 1, metadataOwnerIDIndexes)
}

