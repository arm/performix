func TestGroupingSQL(t *testing.T) {
	harness := jstest.LoadJSModule(t, "recipes/lib/sql_grouping.js")
	groups := []map[string]any{
		{"label": "Group 1", "patterns": []string{`^item\.1\.special$`}},
		{"label": "Group 2's", "patterns": []string{`^item\.1\.`, `^item\.2\.`}},
	}
	expression, err := harness.Call[string](t, "makeGroupingSQL", map[string]any{
		"column": `column"name`, "groups": groups,
	})
	require.NoError(t, err)
	connector, err := duckdb.NewConnector("", nil)
	require.NoError(t, err)
	db := sql.OpenDB(connector)
	t.Cleanup(func() { require.NoError(t, db.Close()) })
	for _, tc := range []struct {
		name  string
		event any
		group string
	}{
		{"broad rule", "item.1.default", "Group 2's"},
		{"specific rule precedes broad rule", "item.1.special", "Group 1"},
		{"second pattern", "item.2.default", "Group 2's"},
		{"unmatched", "other.1.default", "Unclassified"},
		{"operator boundary", "item.10.default", "Unclassified"},
		{"NULL fallback", nil, "Unclassified"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var got string
			// #nosec G202 -- expression is generated by the tested helper; event value is parameterized.
			err := db.QueryRow("SELECT "+expression+` FROM (SELECT ? AS "column""name")`, tc.event).Scan(&got)
			require.NoError(t, err)
			require.Equal(t, tc.group, got)
		})
	}
	for _, tc := range []struct {
		name     string
		patterns []string
		message  string
	}{
		{"empty pattern list", []string{}, "No patterns for group: Second"},
		{"empty pattern", []string{""}, "Empty grouping pattern for: Second"},
		{"duplicate pattern", []string{`^item\.1\.`}, "Duplicate grouping pattern"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			expression, err := harness.Call[string](t, "makeGroupingSQL", map[string]any{
				"column": "value", "groups": []map[string]any{
					{"label": "First", "patterns": []string{`^item\.1\.`}},
					{"label": "Second", "patterns": tc.patterns},
				},
			})
			require.Empty(t, expression)
			require.ErrorContains(t, err, tc.message)
		})
	}
}

func TestGroupingSQLEmptyGroups(t *testing.T) {
	harness := jstest.LoadJSModule(t, "recipes/lib/sql_grouping.js")
	connector, err := duckdb.NewConnector("", nil)
	require.NoError(t, err)
	db := sql.OpenDB(connector)
	t.Cleanup(func() { require.NoError(t, db.Close()) })
	for _, tc := range []struct{ name, fallback, expected string }{
		{"default", "", "Unclassified"},
		{"custom", "Fallback's", "Fallback's"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			args := map[string]any{"column": "value", "groups": []map[string]any{}}
			if tc.fallback != "" {
				args["fallback"] = tc.fallback
			}
			expression, err := harness.Call[string](t, "makeGroupingSQL", args)
			require.NoError(t, err)
			var got string
			// #nosec G202 -- expression is generated by the tested helper.
			err = db.QueryRow("SELECT " + expression).Scan(&got)
			require.NoError(t, err)
			require.Equal(t, tc.expected, got)
		})
	}
}
